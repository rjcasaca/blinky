"""Refresh package inventory/notices from restored application assets (stdlib only).

Run dotnet restore for Blinky.App and Blinky.Mcp first. Framework runtime and
separately downloaded tool/model notices remain in THIRD-PARTY-NOTICES.md.
"""
from pathlib import Path
import xml.etree.ElementTree as ET
import json

root = Path(__file__).resolve().parent.parent
packages = {}
for project in ("Blinky.App", "Blinky.Mcp"):
    assets = json.loads((root / "src" / project / "obj" / "project.assets.json").read_text(encoding="utf-8"))
    for identity, library in assets["libraries"].items():
        if library.get("type") != "package":
            continue
        relative = Path(*library["path"].replace("\\", "/").split("/"))
        folder = next((Path(base) / relative for base in assets["packageFolders"] if (Path(base) / relative).is_dir()), None)
        if folder is None:
            raise RuntimeError("Missing restored package: " + identity)
        metadata = ET.parse(next(folder.glob("*.nuspec"))).getroot().find("{*}metadata")
        def value(name):
            node = metadata.find("{*}" + name)
            return node.text.strip() if node is not None and node.text else ""
        license_node = metadata.find("{*}license")
        if license_node is None:
            raise RuntimeError("Review package without declared license: " + identity)
        declared_license = value("license")
        original_license = None
        if license_node.get("type") == "file":
            original_license = (folder / declared_license).read_text(encoding="utf-8-sig")
            if "MIT" not in original_license:
                raise RuntimeError("Review non-MIT file license: " + identity)
            declared_license = "MIT"
        if declared_license not in ("MIT", "Apache-2.0"):
            raise RuntimeError("Review new license before redistributing: " + identity + " / " + declared_license)
        packages[identity] = (declared_license, value("copyright") or value("authors"), original_license)

license_text = (root / "LICENSE").read_text(encoding="utf-8")
mit_permissions = "Permission is hereby granted" + license_text.split("Permission is hereby granted", 1)[1]
inventory = ["# Resolved package dependencies", "",
    "Generated by `python scripts/dependency-notices.py` from the restored desktop and MCP project assets. This includes direct and transitive NuGet packages; framework runtimes and separately downloaded tools/models are described in [THIRD-PARTY-NOTICES.md](THIRD-PARTY-NOTICES.md).", "",
    "The package metadata supplies the version, license and copyright/author attribution below. Full retained package permission notices are in [licenses/Dependency-Notices.txt](licenses/Dependency-Notices.txt). These components retain their own licenses and are not relicensed as Blinky code.", "",
    "| Package | Version | License | Declared copyright / author |", "| --- | --- | --- | --- |"]
notices = ["Third-party NuGet dependency notices", "",
    "Generated from restored package metadata and declared package license files.",
    "Components retain their own licenses. See DEPENDENCIES.md and THIRD-PARTY-NOTICES.md.", ""]
for identity, (license_id, copyright, original_license) in sorted(packages.items(), key=lambda entry: entry[0].lower()):
    name, version = identity.rsplit("/", 1)
    inventory.append(f"| [{name}](https://www.nuget.org/packages/{name}/{version}) | {version} | {license_id} | {copyright.replace('|', '/')} |")
    notices.extend(["=" * 72, identity, copyright, "License: " + license_id, ""])
    if original_license:
        notices.append(original_license.rstrip())
    elif license_id == "MIT":
        notices.append(mit_permissions.rstrip())
    else:
        notices.append("Licensed under the Apache License, Version 2.0. The complete license is retained in MCP-Apache-2.0.txt in this directory.\nLicense URL: https://www.apache.org/licenses/LICENSE-2.0")
    notices.append("")
(root / "DEPENDENCIES.md").write_text("\n".join(inventory) + "\n", encoding="utf-8")
(root / "licenses" / "Dependency-Notices.txt").write_text("\n".join(notices).rstrip() + "\n", encoding="utf-8")
print(f"Inventoried {len(packages)} restored packages and retained permission notices.")
